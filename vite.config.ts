import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { execFileSync, spawnSync } from 'node:child_process';
import tailwindcss from '@tailwindcss/vite';
import react from '@vitejs/plugin-react';
import path from 'path';
import { defineConfig, loadEnv, type Plugin } from 'vite';
import { VitePWA } from 'vite-plugin-pwa';

interface AndroidSigningConfig {
  applicationId: string;
  versionName: string;
  versionCode: number;
  keystorePath: string;
  keyAlias: string;
  keystorePasswordEnvVar: string;
  keyPasswordEnvVar: string;
  sha256FingerprintPlaceholder: string;
  appHost: string;
}

function commandExists(cmd: string): boolean {
  const probe = spawnSync('which', [cmd], { stdio: 'ignore' });
  return probe.status === 0;
}

function androidAabExportPlugin(options: {
  enabled: boolean;
  signing: AndroidSigningConfig;
}): Plugin {
  return {
    name: 'android-aab-export',
    apply: 'build',
    closeBundle() {
      if (!options.enabled) return;

      const rootDir = import.meta.dirname;
      const distDir = path.resolve(rootDir, 'dist');
      const androidDir = path.resolve(rootDir, 'android');
      const outputDir = path.resolve(androidDir, 'output');
      const wellKnownDistDir = path.resolve(distDir, '.well-known');

      mkdirSync(androidDir, { recursive: true });
      mkdirSync(outputDir, { recursive: true });
      mkdirSync(wellKnownDistDir, { recursive: true });

      const { signing } = options;
      const baseOrigin = `https://${signing.appHost}`;

      // 1. Keep Bubblewrap TWA manifest synchronized with current signing & Play Console metadata
      const twaManifestPath = path.resolve(androidDir, 'twa-manifest.json');
      let existingManifest: Record<string, unknown> = {};
      if (existsSync(twaManifestPath)) {
        try {
          existingManifest = JSON.parse(readFileSync(twaManifestPath, 'utf-8'));
        } catch {
          existingManifest = {};
        }
      }

      const updatedManifest = {
        ...existingManifest,
        packageId: signing.applicationId,
        host: signing.appHost,
        name: 'All in One Skill',
        launcherName: 'AllInOne',
        display: 'standalone',
        themeColor: '#0F172A',
        backgroundColor: '#F8FAFC',
        startUrl: '/',
        iconUrl: `${baseOrigin}/pwa-512x512.png`,
        maskableIconUrl: `${baseOrigin}/pwa-maskable-512x512.png`,
        monochromeIconUrl: `${baseOrigin}/pwa-192x192.png`,
        webManifestUrl: `${baseOrigin}/manifest.webmanifest`,
        fullScopeUrl: `${baseOrigin}/`,
        appVersionName: signing.versionName,
        appVersionCode: signing.versionCode,
        appVersion: signing.versionName,
        minSdkVersion: 21,
        signingKey: {
          path: signing.keystorePath,
          alias: signing.keyAlias,
        },
        fingerprints: signing.sha256FingerprintPlaceholder
          ? [{ value: signing.sha256FingerprintPlaceholder }]
          : [],
      };
      writeFileSync(twaManifestPath, `${JSON.stringify(updatedManifest, null, 2)}\n`, 'utf-8');

      // 2. Write Digital Asset Links (assetlinks.json) with SHA-256 fingerprint placeholder into dist/.well-known
      const assetLinks = [
        {
          relation: ['delegate_permission/common.handle_all_urls'],
          target: {
            namespace: 'android_app',
            package_name: signing.applicationId,
            sha256_cert_fingerprints: [signing.sha256FingerprintPlaceholder],
          },
        },
      ];
      writeFileSync(
        path.resolve(wellKnownDistDir, 'assetlinks.json'),
        `${JSON.stringify(assetLinks, null, 2)}\n`,
        'utf-8'
      );

      // 3. Emit Gradle release signing configuration placeholders for Google Play Console .aab submission
      const signingGradle = `// Auto-generated by vite.config.ts (--mode export-android)
// Loads signing credentials from android/signing.properties or environment variables.
def signingPropsFile = rootProject.file("signing.properties")
def signingProps = new Properties()
if (signingPropsFile.exists()) {
    signingProps.load(new FileInputStream(signingPropsFile))
}

android {
    defaultConfig {
        applicationId "${signing.applicationId}"
        versionCode ${signing.versionCode}
        versionName "${signing.versionName}"
        minSdk 21
        targetSdk 35
    }

    signingConfigs {
        release {
            def storePath = System.getenv("ANDROID_KEYSTORE_PATH") ?: signingProps.getProperty("storeFile", "${signing.keystorePath}")
            storeFile file(storePath)
            storePassword System.getenv("${signing.keystorePasswordEnvVar}") ?: signingProps.getProperty("storePassword", "REPLACE_WITH_KEYSTORE_PASSWORD")
            keyAlias System.getenv("ANDROID_KEY_ALIAS") ?: signingProps.getProperty("keyAlias", "${signing.keyAlias}")
            keyPassword System.getenv("${signing.keyPasswordEnvVar}") ?: signingProps.getProperty("keyPassword", "REPLACE_WITH_KEY_PASSWORD")
        }
    }

    buildTypes {
        release {
            minifyEnabled true
            shrinkResources true
            signingConfig signingConfigs.release
        }
    }

    bundle {
        language { enableSplit = true }
        density { enableSplit = true }
        abi { enableSplit = true }
    }
}
`;
      writeFileSync(path.resolve(androidDir, 'signing-config.gradle'), signingGradle, 'utf-8');

      const hasJava = commandExists('java');
      const hasAndroidSdk = Boolean(process.env.ANDROID_HOME || process.env.ANDROID_SDK_ROOT);

      console.log('\n[export-android] Prepared Google Play (.aab) packaging configuration:');
      console.log(`  - Web bundle output: ${distDir}`);
      console.log(`  - Digital Asset Links: ${path.resolve(wellKnownDistDir, 'assetlinks.json')}`);
      console.log(`  - TWA manifest: ${twaManifestPath}`);
      console.log(`  - Signing config template: ${path.resolve(androidDir, 'signing-config.gradle')}`);

      if (!hasJava || !hasAndroidSdk) {
        const missing: string[] = [];
        if (!hasJava) missing.push('Java JDK 17+ (`java`)');
        if (!hasAndroidSdk) missing.push('Android SDK (`ANDROID_HOME` / `ANDROID_SDK_ROOT`)');

        console.warn(
          `\n[export-android] Skipping native .aab binary compilation: missing ${missing.join(' and ')}.`
        );
        console.warn(
          '[export-android] Fill android/signing.properties (from android/signing.properties.example) and run on a machine with JDK 17 + Android SDK or via GitHub Actions (.github/workflows/build-android-apk.yml) to emit android/output/all-in-one-skill-playstore.aab.\n'
        );

        if (process.env.REQUIRE_NATIVE_AAB === 'true') {
          throw new Error(
            `Cannot compile .aab binary: missing ${missing.join(' and ')}.`
          );
        }
        return;
      }

      // 4. Native Android toolchain available -> compile signed Google Play .aab bundle via Bubblewrap CLI
      const buildDir = path.resolve(androidDir, '.bubblewrap-project');
      mkdirSync(buildDir, { recursive: true });
      writeFileSync(
        path.resolve(buildDir, 'twa-manifest.json'),
        `${JSON.stringify(updatedManifest, null, 2)}\n`,
        'utf-8'
      );

      console.log('[export-android] Java & Android SDK detected. Building signed .aab via @bubblewrap/cli...');
      execFileSync(
        'npx',
        ['--yes', '@bubblewrap/cli', 'update', `--manifest=${baseOrigin}/manifest.webmanifest`],
        { cwd: buildDir, stdio: 'inherit' }
      );
      execFileSync(
        'npx',
        ['--yes', '@bubblewrap/cli', 'build', '--skipPwaValidation'],
        { cwd: buildDir, stdio: 'inherit' }
      );

      const generatedAab = path.resolve(buildDir, 'app-release-bundle.aab');
      if (existsSync(generatedAab)) {
        const destAab = path.resolve(outputDir, 'all-in-one-skill-playstore.aab');
        writeFileSync(destAab, readFileSync(generatedAab));
        console.log(`[export-android] Google Play Console AAB ready: ${destAab}`);
      }
    },
  };
}

export default defineConfig(({ mode }) => {
  const env = loadEnv(mode, process.cwd(), '');
  const isAndroidExport = mode === 'export-android';

  let appHost = 'ais-pre-qo3kxiduq6rs3dhqtxynxu-828642031036.asia-northeast1.run.app';
  const configuredAppUrl = env.APP_URL || process.env.APP_URL;
  if (configuredAppUrl && configuredAppUrl !== 'MY_APP_URL') {
    try {
      appHost = new URL(configuredAppUrl).host;
    } catch {
      // keep default host
    }
  }

  const androidSigning: AndroidSigningConfig = {
    applicationId: env.ANDROID_APPLICATION_ID || 'com.allinoneskill.mumbai',
    versionName: env.ANDROID_VERSION_NAME || '1.0.0',
    versionCode: Number(env.ANDROID_VERSION_CODE || 1),
    keystorePath: env.ANDROID_KEYSTORE_PATH || './android.keystore',
    keyAlias: env.ANDROID_KEY_ALIAS || 'allinoneskill',
    keystorePasswordEnvVar: 'ANDROID_KEYSTORE_PASSWORD',
    keyPasswordEnvVar: 'ANDROID_KEY_PASSWORD',
    sha256FingerprintPlaceholder:
      env.ANDROID_SHA256_FINGERPRINT ||
      '00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00',
    appHost,
  };

  return {
    plugins: [
      react(),
      tailwindcss(),
      VitePWA({
        registerType: 'autoUpdate',
        includeAssets: [
          'icon.svg',
          'apple-touch-icon.png',
          'pwa-192x192.png',
          'pwa-512x512.png',
          'pwa-maskable-512x512.png',
        ],
        manifest: {
          id: '/',
          name: 'All in One Skill',
          short_name: 'AllInOne',
          description:
            'AI-powered service, product, contractor, and skilled workforce marketplace starting in Mumbai, Maharashtra.',
          theme_color: '#0F172A',
          background_color: '#F8FAFC',
          display: 'standalone',
          start_url: '/',
          scope: '/',
          icons: [
            {
              src: '/pwa-192x192.png',
              sizes: '192x192',
              type: 'image/png',
              purpose: 'any',
            },
            {
              src: '/pwa-512x512.png',
              sizes: '512x512',
              type: 'image/png',
              purpose: 'any',
            },
            {
              src: '/pwa-maskable-512x512.png',
              sizes: '512x512',
              type: 'image/png',
              purpose: 'maskable',
            },
          ],
        },
        workbox: {
          globPatterns: ['**/*.{js,css,html,ico,png,svg,woff,woff2}'],
          maximumFileSizeToCacheInBytes: 5 * 1024 * 1024,
        },
        devOptions: {
          enabled: true,
          type: 'module',
        },
      }),
      androidAabExportPlugin({
        enabled: isAndroidExport,
        signing: androidSigning,
      }),
    ],
    build: {
      outDir: 'dist',
      sourcemap: isAndroidExport ? false : false,
    },
    resolve: {
      alias: {
        '@': path.resolve(import.meta.dirname, '.'),
      },
    },
    server: {
      // HMR is disabled in AI Studio via DISABLE_HMR env var.
      // Do not modify—file watching is disabled to prevent flickering during agent edits.
      hmr: process.env.DISABLE_HMR !== 'true',
      // Disable file watching when DISABLE_HMR is true to save CPU during agent edits.
      watch: process.env.DISABLE_HMR === 'true' ? null : {},
    },
  };
});
